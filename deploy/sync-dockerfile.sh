#!/bin/sh
# Regenerates web/Dockerfile.huru from upstream's web/Dockerfile. Run after every upstream merge.
# Changes: the Gym visual exercise media (licensed to openGym only) is not copied into the image,
# the frontend is built with the Huru GYM brand (frontend/src/lib/brand.js + brand/huru/), and the
# image labels are rebranded.
set -eu
cd "$(dirname "$0")/.."
{
  printf '%s\n' '# Huru GYM: generated from web/Dockerfile by deploy/sync-dockerfile.sh - do not edit by hand.'
  printf '%s
' '# Changes: Huru GYM brand at build time; no Gym visual exercise media (see catalogue/media/NOTICE.md).'
  tr -d '\r' < web/Dockerfile \
    | sed -e 's#^COPY catalogue/media/ /usr/share/nginx/html/exercise-media/#COPY catalogue/media/NOTICE.md /usr/share/nginx/html/exercise-media/NOTICE.md#' \
          -e 's#org.opencontainers.image.title="opengym-web"#org.opencontainers.image.title="huru-gym-web"#' \
          -e 's#org.opencontainers.image.source="[^"]*"#org.opencontainers.image.source="https://github.com/epipra/huru-gym"#'     | awk '
        /^RUN APP_BUILD="\$APP_BUILD" npm run build$/ {
          print "# Huru GYM brand (frontend/src/lib/brand.js reads these at build time)."
          print "ARG VITE_APP_NAME=\"Huru GYM\""
          print "ARG VITE_SOURCE_URL=https://github.com/epipra/huru-gym"
          print "ARG VITE_SITE_HOST=gym.epipra.com"
          print "ARG VITE_EXERCISE_MEDIA=0"
          print "ENV VITE_APP_NAME=$VITE_APP_NAME VITE_SOURCE_URL=$VITE_SOURCE_URL VITE_SITE_HOST=$VITE_SITE_HOST VITE_EXERCISE_MEDIA=$VITE_EXERCISE_MEDIA"
          print
          print "COPY brand/huru/ /app/brand/huru/"
          print "RUN APP_NAME=\"$VITE_APP_NAME\" sh /app/brand/huru/apply-dist.sh /app/frontend/dist"
          found = 1
          next
        }
        { print }
        END { if (!found) exit 3 }'
} > web/Dockerfile.huru
grep -q 'COPY catalogue/media/NOTICE.md' web/Dockerfile.huru || { echo "media COPY line changed upstream - update this script" >&2; exit 1; }
# BuildKit reads web/Dockerfile.huru.dockerignore instead of the root .dockerignore: same rules,
# plus the media folders, so 200+ MB of unlicensed media never enters the build context.
{
  printf '%s
' '# Generated by deploy/sync-dockerfile.sh from /.dockerignore - do not edit by hand.'
  tr -d '' < .dockerignore
  printf '%s
' 'catalogue/media/clip' 'catalogue/media/still'
} > web/Dockerfile.huru.dockerignore
echo "web/Dockerfile.huru (+ .dockerignore) regenerated"
